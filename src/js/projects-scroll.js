/* ===========================================================================
   PROJECTS SLIDER (scroll-driven)
   Slides are real HTML generated by scripts/build-projects.js (good for SEO).
   This file only MOVES them: pin the section, slide each project in from the
   right, update the 01 / 04 counter, and snap so one project is shown at a time.
   The last slide is "View more projects" and is not counted as a project.
   =========================================================================== */
import { gsap } from './gsap-setup.js';
import { ScrollTrigger } from 'gsap/ScrollTrigger';
gsap.registerPlugin(ScrollTrigger);

const pin = document.getElementById('pj-pin');
const slides = gsap.utils.toArray('#pj-stage .pj-slide');
const cur = document.getElementById('pj-cur');
const pad = n => String(n).padStart(2, '0');

if (pin && slides.length > 1) {
  const reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  if (reduce) {
    pin.classList.add('pj-static');
  } else {
    const steps = slides.length - 1;
    const projectCount = slides.length - 1;
    const trigger = document.getElementById('projects') || pin;

    if (cur) cur.textContent = '01';

    // Later slides sit on top of earlier ones; all but the first wait off-screen right
    slides.forEach((s, i) => gsap.set(s, { zIndex: i + 1 }));
    gsap.set(slides.slice(1), { xPercent: 100 });

    // Only the visible slide can be reached with the keyboard / screen reader
    let active = -1;
    const setActive = i => {
      if (i === active) return;
      active = i;
      slides.forEach((s, k) => { s.inert = k !== i; });
    };
    setActive(0);

    const tl = gsap.timeline({
      defaults: { ease: 'none' },
      scrollTrigger: {
        trigger,
        start: 'top top',
        end: () => '+=' + trigger.offsetHeight * steps,
        pin: true,
        scrub: 0.6,
        snap: { snapTo: 1 / steps, duration: { min: 0.2, max: 0.6 }, ease: 'power1.inOut' },
        invalidateOnRefresh: true,
        onUpdate: self => {
          const i = Math.round(self.progress * steps);
          if (cur) cur.textContent = pad(Math.min(i + 1, projectCount));
          setActive(i);
        },
      },
    });

    for (let i = 1; i < slides.length; i++) {
      tl.to(slides[i], { xPercent: 0, duration: 1 })
        .to(slides[i - 1], { xPercent: -30, duration: 1 }, '<');
    }

    ScrollTrigger.sort();

    const refresh = () => ScrollTrigger.refresh();
    window.addEventListener('load', () => {
      refresh();
      // After the page has loaded, fetch the waiting slides' photos so they are ready
      const warm = () => slides.forEach(s => {
        const img = s.querySelector('img');
        if (img) img.loading = 'eager';
      });
      (window.requestIdleCallback || (f => setTimeout(f, 1200)))(warm);
    });
    if (document.fonts && document.fonts.ready) document.fonts.ready.then(refresh);
  }
}